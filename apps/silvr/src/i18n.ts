/** "1996 · Disposable" → "1996 · 일회용" in Korean. */
export function cameraEra(era: string): string {
  if (signalLang.value !== 'ko') return era;
  const [year, kind] = era.split(' · ');
  return kind ? `${year} · ${ERA_KO[kind] ?? kind}` : era;
}

export function cameraDescription(id: string): string {
  return (signalLang.value === 'ko' ? cameraKo : cameraEn)[id] ?? '';
}

export type ResolvedLang = 'ko' | 'en';

export function detectLang(): ResolvedLang {
  const langs = typeof navigator !== 'undefined' ? navigator.languages ?? [navigator.language] : [];
  return langs.some((l) => l?.toLowerCase().startsWith('ko')) ? 'ko' : 'en';
}

export function translate(lang: ResolvedLang, key: MsgKey, vars?: Record<string, string | number>): string {
  let s = (lang === 'ko' ? ko : en)[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}

/** Translate using the current UI language. */
export function t(key: MsgKey, vars?: Record<string, string | number>): string {
  return translate(signalLang.value, key, vars);
}

export function stockDescription(id: string): string {
  return (signalLang.value === 'ko' ? stockKo : stockEn)[id] ?? '';
}

